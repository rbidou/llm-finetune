"""The Flask application factory and the page routes.

Threaded on purpose: a stage runs in a worker thread while the browser holds a
server-sent-events connection open to watch it, so a single-threaded server
would deadlock on the first fine-tune.

Page routes render a template and nothing else. Every decision is made in the
engine, reached through the JSON API in :mod:`llmft.web.api`.
"""

from __future__ import annotations

from pathlib import Path

from flask import Flask, Response, abort, redirect, render_template, send_file, url_for

from llmft import __version__
from llmft.web.api import MAX_DATASET_SIZE, api
from llmft.web.jobs import JobRunner

DEFAULT_HOST = "127.0.0.1"
DEFAULT_PORT = 5000

PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
MANUAL_PDF = PROJECT_ROOT / "docs" / "llm-finetune-manual.pdf"

# The online subset of the manual, generated by docs/build_docs.py. Included by
# the documentation page rather than fetched, so it needs no route of its own.
MANUAL_FRAGMENT = Path(__file__).resolve().parent / "templates" / "manual.html"


def create_app() -> Flask:
    """Build the application, with one job runner shared by every request."""
    app = Flask(__name__)
    # Jinja caches templates for the process lifetime unless told otherwise, so
    # without this an edited page keeps serving the old markup until a restart.
    app.jinja_env.auto_reload = True
    app.config["TEMPLATES_AUTO_RELOAD"] = True
    # The same ceiling the dataset endpoint and the browser enforce, applied
    # before a body is read rather than after it has been written to disk.
    app.config["MAX_CONTENT_LENGTH"] = MAX_DATASET_SIZE
    app.extensions["llmft_jobs"] = JobRunner()
    app.register_blueprint(api)

    @app.context_processor
    def inject_version() -> dict[str, str]:
        """Put the release number in every page's footer."""
        return {"version": __version__}

    @app.get("/")
    def index() -> Response:
        """Send an arriving browser to the first step of the pipeline."""
        return redirect(url_for("page_finetune"))

    @app.get("/finetune")
    def page_finetune() -> str:
        """Render the Fine-tune page."""
        return render_template("app/finetune.html")

    @app.get("/quantize")
    def page_quantize() -> str:
        """Render the Quantize page."""
        return render_template("app/quantize.html")

    @app.get("/deploy")
    def page_deploy() -> str:
        """Render the Deploy page."""
        return render_template("app/deploy.html")

    @app.get("/environment")
    def page_environment() -> str:
        """Render the Environment page."""
        return render_template("app/environment.html")

    @app.get("/setup")
    def page_setup() -> str:
        """Render the Setup page."""
        return render_template("app/setup.html")

    @app.get("/documentation")
    def page_documentation() -> str:
        """Render the online subset of the manual.

        The subset is a generated template. When it has not been built the page
        still renders, saying how to build it, rather than failing to load.
        """
        return render_template("app/documentation.html", manual_available=MANUAL_FRAGMENT.is_file())

    @app.get("/manual.pdf")
    def download_manual() -> Response:
        """The full manual, including the parts the online subset leaves out."""
        if not MANUAL_PDF.is_file():
            abort(404, "The manual has not been built. Run: python docs/build_docs.py")
        return send_file(MANUAL_PDF, as_attachment=True, download_name=MANUAL_PDF.name)

    return app


def serve(host: str = DEFAULT_HOST, port: int = DEFAULT_PORT) -> int:
    """Run the development server. Returns a process exit code.

    Bound to the loopback address by default: this exposes local model files and
    starts processes, and is not built to face a network.
    """
    create_app().run(host=host, port=port, threaded=True, debug=False)
    return 0
